// Writes src/tokens.css from design/tokens.json (DTCG, both themes), so no
// design value is ever copied by hand. Run: bun scripts/tokens-css.ts
import { BunFileSystem, BunRuntime } from '@effect/platform-bun'
import { Console, Effect, FileSystem, Schema } from 'effect'

const SRC = new URL('../design/tokens.json', import.meta.url).pathname
const OUT = new URL('../src/tokens.css', import.meta.url).pathname

type Dimension = { value: number; unit: string }
type Leaf = { $type: string; $value: string | number | string[] | Dimension }
type Group = { [key: string]: Group | Leaf }

const isLeaf = (node: Group | Leaf): node is Leaf => '$value' in node

const css = (leaf: Leaf): string => {
  const v = leaf.$value
  if (Array.isArray(v)) return v.map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', ')
  if (typeof v === 'object') return `${v.value}${v.unit}`
  return String(v)
}

const px = (leaf: Leaf): number => (leaf.$value as Dimension).value

// Flattens a group into `--prefix-key: value;` lines.
const vars = (prefix: string, group: Group): ReadonlyArray<string> =>
  Object.entries(group).flatMap(([key, node]) =>
    isLeaf(node) ? [`  --${prefix}-${key}: ${css(node)};`] : vars(`${prefix}-${key}`, node),
  )

const block = (selector: string, lines: ReadonlyArray<string>) =>
  `${selector} {\n${lines.join('\n')}\n}`

// One grid row per width: h2 is 0.7 x h1 rounded; the lead is body + 2 px.
const grid = (row: Group): ReadonlyArray<string> => {
  const leaf = (key: string) => row[key] as Leaf
  return [
    `  --gutter: ${css(leaf('gutter'))};`,
    `  --content-max: ${px(leaf('content')) + 2 * px(leaf('gutter'))}px;`,
    `  --h1-size: ${css(leaf('h1'))};`,
    `  --h2-size: ${Math.round(px(leaf('h1')) * 0.7)}px;`,
    `  --body-size: ${css(leaf('body'))};`,
    `  --lead-size: ${px(leaf('body')) + 2}px;`,
    `  --code-size: ${css(leaf('mono'))};`,
    `  --section-gap: ${css(leaf('section-gap'))};`,
  ]
}

// One line per width keeps the generated file short.
const widthLine = (width: string, row: Group) =>
  `@media (min-width: ${width}px) { :root { ${grid(row)
    .map((line) => line.trim())
    .join(' ')} } }`

const render = (tokens: Group): string => {
  const color = tokens.color as Group
  const widths = Object.entries(tokens.breakpoint as Group).sort(
    ([a], [b]) => Number(a) - Number(b),
  )
  const [[, first], ...rest] = widths
  const root = [
    '  color-scheme: light dark;',
    ...vars('color', color.light as Group),
    ...vars('font', tokens.font as Group),
    ...vars('line-height', tokens['line-height'] as Group),
    ...vars('space', tokens.space as Group),
    ...vars('radius', tokens.radius as Group),
    ...vars('size', tokens.size as Group),
    ...grid(first as Group),
  ]
  const dark = vars('color', color.dark as Group)
  return [
    '/* Generated by scripts/tokens-css.ts from design/tokens.json. Do not edit. */',
    block(':root', root),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', dark)}\n}`,
    block(':root[data-theme="dark"]', dark),
    ...rest.map(([width, row]) => widthLine(width, row as Group)),
    '',
  ].join('\n\n')
}

const decodeTokens = Schema.decodeUnknownEffect(
  Schema.fromJsonString(Schema.Record(Schema.String, Schema.Unknown)),
)

const program = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem
  const tokens = (yield* decodeTokens(yield* fs.readFileString(SRC))) as Group
  const out = render(tokens)
  yield* fs.writeFileString(OUT, out)
  yield* Console.log(`tokens-css: wrote ${OUT} (${out.split('\n').length} lines)`)
})

program.pipe(Effect.provide(BunFileSystem.layer), BunRuntime.runMain)
