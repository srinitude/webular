// Writes src/grid.css, the per-width grid, from the dev.webular.grid rows in
// design/tokens.json, and src/semantic.css, the semantic light and dark colors
// with their primitive aliases resolved. src/tokens.css (every other token, both
// themes) comes from the design-loop build_platform_tokens builder.
// Run: bun scripts/tokens-css.ts
import { BunFileSystem, BunRuntime } from '@effect/platform-bun'
import { Console, Effect, FileSystem, Schema } from 'effect'

const SRC = new URL('../design/tokens.json', import.meta.url).pathname
const OUT = new URL('../src/grid.css', import.meta.url).pathname
const SEMANTIC_OUT = new URL('../src/semantic.css', import.meta.url).pathname
const HEADER = '/* Generated by scripts/tokens-css.ts from design/tokens.json. Do not edit. */'

type Dimension = { value: number; unit: string }
type Leaf = { $type: string; $value: Dimension }
type Row = { [key: string]: Leaf }

const css = (leaf: Leaf) => `${leaf.$value.value}${leaf.$value.unit}`
const px = (leaf: Leaf) => leaf.$value.value

// One grid row per width: h2 is 0.7 x h1 rounded; the run line is 1.25 x h1; the lead is body + 2 px.
const grid = (row: Row): ReadonlyArray<string> => [
  `--gutter: ${css(row.gutter)};`,
  `--content-max: ${px(row.content) + 2 * px(row.gutter)}px;`,
  `--h1-size: ${css(row.h1)};`,
  `--h2-size: ${Math.round(px(row.h1) * 0.7)}px;`,
  `--run-line-size: ${px(row.h1) * 1.25}px;`,
  `--body-size: ${css(row.body)};`,
  `--lead-size: ${px(row.body) + 2}px;`,
  `--code-size: ${css(row.mono)};`,
  `--section-gap: ${css(row['section-gap'])};`,
]

// One line per width keeps the generated file short.
const widthLine = (width: string, row: Row) =>
  `@media (min-width: ${width}px) { :root { ${grid(row).join(' ')} } }`

const render = (rows: Record<string, unknown>): string =>
  [
    HEADER,
    ...Object.entries(rows)
      .filter(([width]) => /^\d+$/.test(width))
      .sort(([a], [b]) => Number(a) - Number(b))
      .map(([width, row]) => widthLine(width, row as Row)),
    '',
  ].join('\n\n')

const Colors = Schema.Record(Schema.String, Schema.Struct({ $value: Schema.String }))

const Tokens = Schema.fromJsonString(
  Schema.Struct({
    primitive: Schema.Struct({ palette: Colors }),
    semantic: Schema.Struct({ light: Colors, dark: Colors }),
    $extensions: Schema.Struct({
      'dev.webular.grid': Schema.Record(Schema.String, Schema.Unknown),
    }),
  }),
)
type Tokens = typeof Tokens.Type

// A semantic value is a color or a {primitive.palette.<name>} alias, resolved to its color.
// Lowercase hex matches what Biome writes, so a rebuild leaves no diff.
const semanticColors = (tokens: Tokens, mode: 'light' | 'dark') =>
  Object.entries(tokens.semantic[mode]).map(([name, leaf]) => {
    const alias = /^\{primitive\.palette\.([\w-]+)\}$/.exec(leaf.$value)?.[1]
    const value = alias === undefined ? leaf.$value : tokens.primitive.palette[alias]?.$value
    return { name, raw: leaf.$value, value: value?.toLowerCase() }
  })

const block = (colors: ReturnType<typeof semanticColors>, indent: string) =>
  colors.map(({ name, value }) => `${indent}--semantic-${name}: ${value};`).join('\n')

// Light on :root. Dark follows the system unless the theme toggle picked light, and always under data-theme="dark".
const renderSemantic = Effect.fn('renderSemantic')(function* (tokens: Tokens) {
  const light = semanticColors(tokens, 'light')
  const dark = semanticColors(tokens, 'dark')
  const missing = [...light, ...dark].filter(({ value }) => value === undefined)
  if (missing.length > 0)
    return yield* Effect.fail(`tokens-css: missing colors: ${missing.map((c) => c.raw).join(', ')}`)
  return [
    HEADER,
    `:root {\n${block(light, '  ')}\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${block(dark, '    ')}\n  }\n}`,
    `:root[data-theme="dark"] {\n${block(dark, '  ')}\n}`,
    '',
  ].join('\n')
})

const program = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem
  const tokens = yield* Schema.decodeUnknownEffect(Tokens)(yield* fs.readFileString(SRC))
  const out = render(tokens.$extensions['dev.webular.grid'])
  yield* fs.writeFileString(OUT, out)
  yield* Console.log(`tokens-css: wrote ${OUT} (${out.split('\n').length} lines)`)
  const semantic = yield* renderSemantic(tokens)
  yield* fs.writeFileString(SEMANTIC_OUT, semantic)
  yield* Console.log(`tokens-css: wrote ${SEMANTIC_OUT} (${semantic.split('\n').length} lines)`)
})

program.pipe(Effect.provide(BunFileSystem.layer), BunRuntime.runMain)
