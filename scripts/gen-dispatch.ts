// Generates src/cli/dispatch-table.ts from mise.toml's run:* tasks, so the CLI
// starts each command straight from the table mise.toml defines, with no mise
// process per call. `mise run build` runs it first; a test fails on drift.
import { join } from 'node:path'
import { Effect, FileSystem } from 'effect'
import { runMain } from '../src/core/effect.ts'

const ENTRY = /\{\{vars\.commands\}\}\/([a-z]+)\.\{\{vars\.ext\}\}"$/

type Tasks = Record<string, { run?: unknown }>

// run:<name> -> the command file stem its run line starts.
export function tableFrom(config: unknown): Record<string, string> {
  const tasks = (config as { tasks?: Tasks }).tasks ?? {}
  const rows = Object.entries(tasks).flatMap(([task, def]) => {
    const stem = typeof def.run === 'string' ? ENTRY.exec(def.run)?.[1] : undefined
    return task.startsWith('run:') && stem ? [[task.slice(4), stem] as const] : []
  })
  return Object.fromEntries(rows.sort(([a], [b]) => a.localeCompare(b)))
}

export function render(table: Record<string, string>): string {
  const rows = Object.entries(table).map(([name, stem]) => `  ${name}: '${stem}',`)
  return [
    '// Generated by scripts/gen-dispatch.ts from the run:* tasks in mise.toml. Do not edit.',
    'export const DISPATCH = {',
    ...rows,
    '} as const',
    '',
  ].join('\n')
}

export const readTable = (root: string) =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem
    const toml = yield* fs.readFileString(join(root, 'mise.toml'))
    return tableFrom(yield* Effect.try(() => Bun.TOML.parse(toml)))
  })

const main = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem
  const root = join(import.meta.dir, '..')
  const table = yield* readTable(root)
  yield* fs.writeFileString(join(root, 'src/cli/dispatch-table.ts'), render(table))
  return 0
})

if (import.meta.main) runMain(main)
